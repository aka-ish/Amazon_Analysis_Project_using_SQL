-- 10. Query the top 10 products by the number of returns and display the
-- return rate as a percentage of total units sold for each product.
select 
    p.product_id,
    p.product_name,
    COUNT(*) as total_units_sold,
    SUM(case when o.order_status = 'Returned' then 1 else 0 end) AS total_returned,
    CAST(SUM(CASE WHEN o.order_status = 'Returned' then 1 else 0 end) as decimal(10,2)) 
        / CAST(COUNT(*) as decimal(10,2)) * 100 as return_percentage
from order_items oi
join products p 
    on oi.product_id = p.product_id
join orders o 
    on o.order_id = oi.order_id
group by 
    p.product_id, 
    p.product_name
order by 
    total_returned desc
limit 10;
-- Month-over-Month Revenue-Growth- > How is revenue changing month over month?

WITH monthly_sales AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS year_months,
        SUM(oi.quantity * oi.price_per_unit) AS revenue
    FROM orders o
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'Completed'
    GROUP BY year_months
)
SELECT
    year_months,
    revenue,
    LAG(revenue) OVER (ORDER BY year_months) AS prev_month_revenue,
    ROUND(
        (revenue - LAG(revenue) OVER (ORDER BY year_months)) * 100.0 /
        LAG(revenue) OVER (ORDER BY year_months),
        2
    ) AS growth_pct
FROM monthly_sales;

-- Top 20% Products contributing to Revenue 
with product_sales as (
select p.product_name, sum(oi.quantity*oi.price_per_unit) as revenue 
from products p 
join order_items oi on p.product_id = oi.product_id
join orders o on oi.order_id = o.order_id 
where o.order_status = 'Completed'
group by p.product_name
),
ranked as(
select *,
sum(revenue) over() as total_revenue,
sum(revenue) over(order by revenue desc) as cumulative_revenue
from product_sales
)
select * from ranked where cumulative_revenue <= total_revenue * 0.8;

