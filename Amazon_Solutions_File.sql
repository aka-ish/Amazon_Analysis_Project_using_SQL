-- 6. Identify the least-selling product category for each state and include the
-- total sales for that category within each state.
with category_sales as (
select
	c.state,
    ct.category_name,
    sum(oi.quantity * oi.price_per_unit) as total_sales
from categories ct
join products p 
	on ct.category_id = p.category_id
join order_items oi 
	on p.product_id = oi.product_id
join orders o 
	on oi.order_id = o.order_id 
join customers c 
	on o.customer_id = c.customer_id 

group by c.state, ct.category_name
),
ranked_categories as (
	select 
		state,
        category_name,
        total_sales,
        row_number() over(partition by state order by total_sales asc) as rn
	from category_sales
)
select state, category_name, total_sales,rn
from ranked_categories
where rn = 1 
order by state;
 
