-- 7. Calculate the customer lifetime value (CLTV) for each customer and
-- rank customers based on their CLTV.
with customer_cltv as (
select 
	c.customer_id, 
	concat(c.first_name,' ',c.last_name) as customer_name, 
    o.order_status, 
    round(sum(oi.quantity * oi.price_per_unit),2) as CLTV
from customers c 
join orders o 
	on c.customer_id = o.customer_id 
join order_items oi 
	on o.order_id = oi.order_id
where o.order_status = 'Completed'
group by c.customer_id, customer_name
)

select 
	customer_id, 
    customer_name, 
    CLTV,
	dense_rank() over(order by cltv desc) as cltv_rank
from customer_cltv
order by cltv desc;


-- 8. Query products with stock levels below a certain threshold (e.g., less
